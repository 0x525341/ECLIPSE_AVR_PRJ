#include "ADC_ATMEGA8.h"
#include <avr/io.h>
//-------------------------------------------------------
void ADC_Init(void)
{
	ADCSRA |= (1<<ADEN) // Разрешение использования АЦП
	|(1<<ADPS2)|(1<<ADPS1)|(1<<ADPS0);//Делитель 128 = 64 кГц
//	ADMUX |= (1<<REFS1)|(1<<REFS0); //Внутренний Источник ОН 2,56в
}
//-------------------------------------------------------
uint16_t ADC_convert (uint8_t adc_channel)
{
	ADMUX=0;
	ADMUX |= (1<<REFS0)|adc_channel;//AVСС с внешним конденсатором  (чтобы не было искажений)
	ADCSRA |= (1<<ADSC); //Начинаем преобразование
	while((ADCSRA & (1<<ADSC))); //проверим закончилось ли аналого-цифровое преобразование
	return (unsigned int) ADC;
}
